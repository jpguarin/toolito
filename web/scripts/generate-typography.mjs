// Turns the type styles of design/tokens.json into Tailwind utilities, so they
// accept variants: `heading wide:display` works, a plain CSS class would not.
// Run after changing tokens.json: npm run tokens:typography
import { readFileSync, writeFileSync } from "node:fs";

const tokensUrl = new URL("../../design/tokens.json", import.meta.url);
const outputUrl = new URL("../src/styles/typography.css", import.meta.url);
const tokens = JSON.parse(readFileSync(tokensUrl, "utf8"));

const lines = ["/* Generated by scripts/generate-typography.mjs from design/tokens.json. Do not edit. */"];
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    lines.push(
      "",
      `@utility ${style.name} {`,
      `  font-family: var(--font-${group.family});`,
      `  font-size: ${style.fontSize};`,
      `  line-height: ${style.lineHeight};`,
      `  font-weight: ${style.fontWeight};`,
    );
    if (style.letterSpacing) lines.push(`  letter-spacing: ${style.letterSpacing};`);
    lines.push("}");
  }
}

writeFileSync(outputUrl, lines.join("\n") + "\n");
console.log(`Wrote ${outputUrl.pathname}`);
